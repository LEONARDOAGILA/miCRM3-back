-- ===========================================================================
-- TIPOS DE USUARIO: DE CUATRO NÚMEROS A FUEGO A UN CATÁLOGO
-- ===========================================================================
-- Fecha: 2026-10-09
-- Se aplica después de 2026-10-09_seguridad_archivos_por_grupo.sql.
--
-- users.type_user era una lista de cuatro valores escrita en el código de
-- Angular (1 SUPER USUARIO, 2 ADMINISTRADOR, 3 USUARIO SISTEMA, 4 USUARIO WEB)
-- y repetida en cinco pantallas. Decidía los permisos del gestor de archivos
-- hasta el fichero anterior, que lo pasó a los grupos; ahora el campo cambia
-- de oficio: pasa a decir QUÉ CLASE DE USUARIO ES —del sistema, de la página
-- web, freelance, temporal—, que es una pregunta distinta de «qué puede
-- hacer», y ésa la contestan el grupo y el perfil.
--
-- LOS DOS PRIMEROS VALORES NO SON CATEGORÍAS, son restos del oficio anterior:
-- «super usuario» y «administrador» describen poder, no clase de persona. Se
-- quedan en el catálogo pero INACTIVOS, para que el historial siga
-- resolviéndose —la auditoría guarda type_user en sus jsonb— y para que la
-- clave ajena no se rompa. Los dos usuarios que tenían el 1 (LAGILA y
-- SISTEMAS-CUENCA, los dos personal interno) pasan a SISTEMA.
--
-- Para deshacer ese movimiento:
--   UPDATE seguridad.users SET type_user = 1 WHERE login_user IN ('LAGILA', 'SISTEMAS-CUENCA');
--
-- LOS IDS 3 Y 4 NO SE TOCAN y por eso no hay que mover 51 filas: ya querían
-- decir SISTEMA y WEB, que es justo lo que se busca. Los nuevos empiezan en 5.
--
-- EL GRUPO DEJA DE ESCRIBIR ESTE CAMPO. fn_grupos_modificar, cuando se marca
-- «Aplicar a sus usuarios», ponía type_user = 2/3/4 según el grupo fuera
-- administrador, de sistema o web. Con el oficio nuevo eso sería pisar la
-- categoría: un freelance puede estar en cualquier grupo. El grupo sigue
-- aplicando perfil y horario, que son suyos.
--
-- Idempotente.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. El catálogo
-- ---------------------------------------------------------------------------
-- Mismo molde que ventas.gestiones_tipos, que es el catálogo que ya hay en la
-- casa: codigo + nombre + orden + activo y las cuatro columnas de auditoría.
--
-- El id es IDENTITY «BY DEFAULT» y no «ALWAYS» a propósito: los cuatro
-- primeros se insertan con su número de siempre, porque users.type_user ya los
-- tiene escritos.
CREATE TABLE IF NOT EXISTS seguridad.tipos_usuarios (
    id          integer     GENERATED BY DEFAULT AS IDENTITY,
    codigo      varchar(20) NOT NULL,
    nombre      varchar(60) NOT NULL,
    descripcion text,
    /** Clase de Font Awesome, para la ficha y las rejillas */
    icono       varchar(40),
    /** Clase de color del tema (bg-primary, bg-info...) para la etiqueta */
    color       varchar(30),
    orden       integer     NOT NULL DEFAULT 100,
    activo      boolean     NOT NULL DEFAULT true,

    created_at  timestamptz DEFAULT CURRENT_TIMESTAMP,
    updated_at  timestamptz DEFAULT CURRENT_TIMESTAMP,
    created_by  varchar(100),
    updated_by  varchar(100),

    CONSTRAINT pk_tipos_usuarios     PRIMARY KEY (id),
    CONSTRAINT uq_tipos_usuarios_cod UNIQUE (codigo),
    CONSTRAINT ck_tipos_usuarios_cod CHECK (codigo = UPPER(TRIM(codigo)) AND length(TRIM(codigo)) >= 3)
);

COMMENT ON TABLE seguridad.tipos_usuarios
    IS 'Qué clase de usuario es (del sistema, web, freelance, temporal). No da permisos: eso lo deciden el grupo y el perfil';

COMMENT ON COLUMN seguridad.users.type_user
    IS 'Clase de usuario: seguridad.tipos_usuarios. No da permisos';

-- Los tres disparadores de siempre de las tablas de seguridad
DROP TRIGGER IF EXISTS trigger_tipos_usuarios_set_users  ON seguridad.tipos_usuarios;
DROP TRIGGER IF EXISTS trigger_tipos_usuarios_updated_at ON seguridad.tipos_usuarios;
DROP TRIGGER IF EXISTS trg_tipos_usuarios_audit          ON seguridad.tipos_usuarios;

CREATE TRIGGER trigger_tipos_usuarios_set_users
    BEFORE INSERT OR UPDATE ON seguridad.tipos_usuarios
    FOR EACH ROW EXECUTE FUNCTION auditoria.fn_set_audit_users();

CREATE TRIGGER trigger_tipos_usuarios_updated_at
    BEFORE UPDATE ON seguridad.tipos_usuarios
    FOR EACH ROW EXECUTE FUNCTION auditoria.fn_update_updated_at_column();

CREATE TRIGGER trg_tipos_usuarios_audit
    AFTER INSERT OR UPDATE OR DELETE ON seguridad.tipos_usuarios
    FOR EACH ROW EXECUTE FUNCTION auditoria.fn_auditar_cambios();


